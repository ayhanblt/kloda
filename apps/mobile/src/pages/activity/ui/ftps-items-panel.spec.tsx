import { act, fireEvent, render, waitFor } from '@testing-library/react-native';
import { AppState, type AppStateStatus } from 'react-native';
import { FtpsItemsPanel } from './ftps-items-panel';
import { ftps } from '../../../shared/api/ftps';
import { ftpsBackups } from '../../../shared/api/ftps-backups';
import { i18n } from '../../../shared/i18n';
jest.mock('../../../shared/api/ftps',() => ({ ftps:{ status:jest.fn() } }));
jest.mock('../../../shared/api/ftps-backups',() => ({ ftpsBackups:{ list:jest.fn(),restore:jest.fn(),copy:jest.fn(),cancel:jest.fn().mockResolvedValue(undefined) } }));
const id = '11111111-1111-4111-8111-111111111111';
const item = { id,name:'owned.json',path:'source/owned.json',kind:'photo_manifest' as const,sha256:'A'.repeat(43),size:'1' };
beforeEach(() => {
  jest.clearAllMocks(); jest.mocked(ftps.status).mockResolvedValue({ supported:true,configured:true,enabled:true,running:false });
  jest.mocked(ftpsBackups.list).mockResolvedValue({ targetId:'A'.repeat(43),items:[item],hasMore:false,canRestoreFiles:true,canRestorePhotos:true });
});
it('cancels a Photos restore on foreground loss and ignores its late success',async () => {
  let listener: (state: AppStateStatus) => void = () => undefined;
  const spy = jest.spyOn(AppState,'addEventListener').mockImplementation((_event,callback) => { listener = callback; return { remove:jest.fn() }; });
  let finish: (value: string) => void = () => undefined;
  jest.mocked(ftpsBackups.restore).mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  const view = await render(<FtpsItemsPanel />);
  await waitFor(() => expect(view.getByText(i18n.t('destinations.ftps.backupsTitle'))).toBeTruthy());
  await fireEvent.press(view.getByRole('button',{ name:i18n.t('destinations.review.refresh') }));
  await waitFor(() => expect(view.getByText(item.name)).toBeTruthy());
  await fireEvent.press(view.getByRole('button',{ name:i18n.t('transfer.photos.restore',{ name:item.name }) }));
  await act(async () => { listener('background'); });
  expect(ftpsBackups.cancel).toHaveBeenCalledWith(expect.any(String),false);
  await act(async () => { finish(item.name); });
  expect(view.queryByText(i18n.t('transfer.backups.restored',{ name:item.name }))).toBeNull();
  await view.unmount(); spy.mockRestore();
});
