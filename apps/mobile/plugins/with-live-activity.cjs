// Step19 iOS Live Activity (approved SwiftUI exception, 2026-10-31): widget extension + app-side intents.
// Generated at prebuild from repository sources only: theme tokens, TR/EN/DE locale keys, Lucide icons, Inter fonts.
const fs = require('fs');
const path = require('path');
const { withDangerousMod, withInfoPlist, withXcodeProject } = require('expo/config-plugins');

const NAME = 'KlodaLiveActivity';
const APP_GROUP = 'KlodaLiveActivityApp';
const LANGUAGES = ['en', 'tr', 'de'];
const DEPLOYMENT_TARGET = '16.4';
const ICONS = ['arrow-up-right', 'check', 'circle-alert', 'monitor', 'pause', 'play'];
const FONTS = ['Inter-Regular.ttf', 'Inter-SemiBold.ttf'];
const KEYS = ['statusUi.states.syncing', 'statusUi.states.waiting', 'statusUi.states.safe', 'statusUi.states.attention',
  'statusUi.states.error', 'statusUi.lines.error', 'statusUi.pause', 'statusUi.resume', 'statusUi.progressLabel',
  'statusUi.progress.operations', 'ui.lockScreen.live', 'ui.lockScreen.open', 'ui.lockScreen.paused', 'ui.lockScreen.pc',
  'ui.providers.webdav'];
const EXTENSION_SOURCES = ['KlodaLiveActivityWidget.swift', 'KlodaLiveActivityViews.swift', 'KlodaLiveActivityCopy.swift',
  'KlodaLiveActivityIntents.swift', 'KlodaBackupAttributes.swift', 'KlodaLiveActivityTheme.swift'];
const APP_SOURCES = ['KlodaLiveActivityIntents.swift', 'KlodaBackupAttributes.swift'];

const mobile = path.resolve(__dirname, '..');
const repo = path.resolve(mobile, '../..');
const read = (file) => fs.readFileSync(file, 'utf8');

function tokens(mode) {
  const block = read(path.join(mobile, 'src/shared/theme/tokens.ts')).match(new RegExp(`const ${mode} = \\{([\\s\\S]*?)\\n\\}`));
  if (!block) throw new Error(`${NAME}: ${mode} tokens not found`);
  return Object.fromEntries([...block[1].matchAll(/"([\w-]+)": "(#[0-9A-Fa-f]{6})"/g)].map((m) => [m[1], m[2]]));
}
// Same sRGB mix as tokens.ts (the app's adaptation of the Lovable color-mix tokens).
function mix(color, background, weight) {
  const ch = (c) => [1, 3, 5].map((o) => parseInt(c.slice(o, o + 2), 16));
  const a = ch(color), b = ch(background);
  return '#' + a.map((v, i) => Math.round(v * weight + b[i] * (1 - weight)).toString(16).padStart(2, '0')).join('');
}
function lockColors(mode) {
  const t = tokens(mode);
  return { lockCard: t.tile, lockText: t['tile-foreground'], lockMuted: mix(t['tile-foreground'], t.tile, 0.72),
    lockTrack: mix(t['tile-foreground'], t.tile, 0.22), lockAccent: t['brand-base'], brand: t['brand-base'], tile: t.tile,
    tileRing: t['tile-ring'], buttonBrand: mode === 'light' ? t['brand-text'] : t['brand-base'], onBrand: t['on-brand'] };
}
function theme() {
  const light = lockColors('light'), dark = lockColors('dark');
  const rgb = (hex) => {
    const [r, g, b] = [1, 3, 5].map((o) => (parseInt(hex.slice(o, o + 2), 16) / 255).toFixed(4));
    return `UIColor(red: ${r}, green: ${g}, blue: ${b}, alpha: 1)`;
  };
  const lines = Object.keys(light).map((key) => `  static let ${key} = Color(UIColor { $0.userInterfaceStyle == .dark ? `
    + `${rgb(dark[key])} : ${rgb(light[key])} })`);
  return `// Generated by plugins/with-live-activity.cjs from src/shared/theme/tokens.ts; do not edit.\nimport SwiftUI\nimport UIKit\n\nenum KlodaTheme {\n${lines.join('\n')}\n}\n`;
}
function strings(language) {
  const locale = JSON.parse(read(path.join(mobile, `src/shared/i18n/locales/${language}.json`)));
  const escape = (v) => v.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
  return KEYS.map((key) => {
    const value = key.split('.').reduce((node, part) => node?.[part], locale);
    if (typeof value !== 'string') throw new Error(`${NAME}: missing ${language} key ${key}`);
    return `"${key}" = "${escape(value)}";`;
  }).join('\n') + '\n';
}
function lucideRoot() {
  let dir = path.dirname(require.resolve('lucide-react-native'));
  while (path.basename(dir) !== 'lucide-react-native') dir = path.dirname(dir);
  return dir;
}
// Lucide icon nodes (lucide-react-native, ISC) as template SVGs: 24 viewBox, stroke 2, round caps/joins.
function icon(name) {
  const source = read(path.join(lucideRoot(), 'dist/esm/icons', `${name}.mjs`));
  const node = source.match(/node: \[([\s\S]*?)\n {2}\]/) ?? source.match(/node: \[(.*)\]/);
  if (!node) throw new Error(`${NAME}: icon ${name} not parsed`);
  const shapes = [...node[1].matchAll(/"(\w+)",\s*\{([^}]*)\}/g)].map(([, tag, body]) => {
    const attrs = [...body.matchAll(/(\w+): "([^"]*)"/g)].filter(([, k]) => k !== 'key').map(([, k, v]) => `${k}="${v}"`);
    return `<${tag} ${attrs.join(' ')}/>`;
  });
  if (!shapes.length) throw new Error(`${NAME}: icon ${name} empty`);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${shapes.join('')}</svg>\n`;
}
function infoPlist() {
  const fonts = FONTS.map((f) => `<string>${f}</string>`).join('');
  const languages = LANGUAGES.map((l) => `<string>${l}</string>`).join('');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleDevelopmentRegion</key><string>en</string>
<key>CFBundleDisplayName</key><string>Kloda</string>
<key>CFBundleExecutable</key><string>$(EXECUTABLE_NAME)</string>
<key>CFBundleIdentifier</key><string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
<key>CFBundleLocalizations</key><array>${languages}</array>
<key>CFBundleName</key><string>$(PRODUCT_NAME)</string>
<key>CFBundlePackageType</key><string>$(PRODUCT_BUNDLE_PACKAGE_TYPE)</string>
<key>CFBundleShortVersionString</key><string>$(MARKETING_VERSION)</string>
<key>CFBundleVersion</key><string>$(CURRENT_PROJECT_VERSION)</string>
<key>UIAppFonts</key><array>${fonts}</array>
<key>NSExtension</key><dict><key>NSExtensionPointIdentifier</key><string>com.apple.widgetkit-extension</string></dict>
</dict></plist>
`;
}
function write(file, content) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, content); }
function writeStrings(root) {
  for (const language of LANGUAGES) write(path.join(root, `${language}.lproj/KlodaLiveActivity.strings`), strings(language));
}

function withFiles(config) {
  return withDangerousMod(config, ['ios', (mod) => {
    const ios = mod.modRequest.platformProjectRoot;
    const extension = path.join(ios, NAME), app = path.join(ios, APP_GROUP);
    for (const file of EXTENSION_SOURCES.filter((f) => f !== 'KlodaLiveActivityTheme.swift')) {
      const source = file === 'KlodaBackupAttributes.swift' ? path.join(mobile, 'modules/my-module/ios', file) : path.join(mobile, 'targets/live-activity', file);
      write(path.join(extension, file), read(source));
      if (APP_SOURCES.includes(file)) write(path.join(app, file), read(source));
    }
    write(path.join(extension, 'KlodaLiveActivityTheme.swift'), theme());
    write(path.join(extension, 'Info.plist'), infoPlist());
    writeStrings(extension); writeStrings(app);
    const assets = path.join(extension, 'Assets.xcassets');
    write(path.join(assets, 'Contents.json'), JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2));
    for (const name of ICONS) {
      write(path.join(assets, `${name}.imageset/${name}.svg`), icon(name));
      write(path.join(assets, `${name}.imageset/Contents.json`), JSON.stringify({ images: [{ filename: `${name}.svg`, idiom: 'universal' }],
        info: { author: 'xcode', version: 1 }, properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' } }, null, 2));
    }
    for (const font of FONTS) fs.copyFileSync(path.join(repo, 'assets/fonts/inter', font), path.join(extension, font));
    return mod;
  }]);
}

module.exports = (config) => {
  config = withInfoPlist(config, (mod) => { mod.modResults.NSSupportsLiveActivities = true; return mod; });
  config = withFiles(config);
  return withXcodeProject(config, (mod) => {
    require('./live-activity-xcode.cjs')(mod.modResults, {
      name: NAME, appGroup: APP_GROUP, languages: LANGUAGES, deploymentTarget: DEPLOYMENT_TARGET, fonts: FONTS,
      extensionSources: EXTENSION_SOURCES, appSources: APP_SOURCES,
      bundleId: `${mod.ios?.bundleIdentifier ?? config.ios.bundleIdentifier}.LiveActivity`,
      version: config.version ?? '1.0.0', build: config.ios?.buildNumber ?? '1',
    });
    return mod;
  });
};
