import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, existsSync, readFileSync, writeFileSync, copyFileSync, cpSync, lstatSync, renameSync } from 'node:fs';
import { join } from 'node:path';
import { root, crate, targetDirectory, requireFile, rustToolchain } from './native-build-common.mjs';

// Source/ABI packaging only. No simulator boot, signing, app install or native owner run.
if (process.platform !== 'darwin') throw new Error('iOS native build requires the Apple SDK on macOS.');
// shortcut: ExpoModulesJSI57.1.1 misses Swift's __ObjC:: spelling; remove when upstream fixes its cleanup.
const jsiDirectory = join(root, 'node_modules/expo-modules-jsi');
const jsiScript = requireFile(join(jsiDirectory, 'apple/scripts/build-xcframework.sh'));
const jsiSource = readFileSync(jsiScript, 'utf8');
const oldCleanup = '/^extension __ObjC\\./,/^}/d';
const newCleanup = '/^extension __ObjC[.:]/,/^}/d';
if (jsiSource.includes(oldCleanup)) {
  assert.equal(JSON.parse(readFileSync(join(jsiDirectory, 'package.json'), 'utf8')).version, '57.1.1',
    'Review the ExpoModulesJSI compatibility workaround for this version');
  assert.equal(jsiSource.split(oldCleanup).length, 2, 'Unexpected ExpoModulesJSI cleanup script');
  writeFileSync(jsiScript, jsiSource.replace(oldCleanup, newCleanup));
} else assert(jsiSource.includes(newCleanup), 'Unrecognized ExpoModulesJSI interface cleanup');
function run(command, args, env = {}, capture = false) {
  const result = spawnSync(command, args, { cwd: root, env: { ...process.env, ...env },
    encoding: 'utf8', maxBuffer: 8 * 1024 * 1024, stdio: capture ? 'pipe' : 'inherit' });
  if (result.error || result.status !== 0) throw new Error(`${command} failed (${result.error?.code ?? result.status}); no iOS package accepted.`);
  return result.stdout?.trim() ?? '';
}
const compiler = requireFile(run('rustup', ['which', '--toolchain', rustToolchain, 'rustc'], {}, true), true);
const simulator = process.arch === 'arm64' ? 'aarch64-apple-ios-sim' : 'x86_64-apple-ios';
assert(['arm64', 'x64'].includes(process.arch), 'Unsupported build host architecture');
const libraries = [];
const symbols = ['open', 'request', 'suspend', 'set_foreground', 'transfer', 'reply_free',
  'background_begin', 'background_end', 'background_transfer', 'lan_with_socket', 'lan_current'];
for (const [target, sdk] of [['aarch64-apple-ios', 'iphoneos'], [simulator, 'iphonesimulator']]) {
  const sdkRoot = run('xcrun', ['--sdk', sdk, '--show-sdk-path'], {}, true);
  run('rustup', ['run', rustToolchain, 'cargo', 'rustc', '--locked', '--offline', '--no-default-features',
    '--manifest-path', join(crate, 'Cargo.toml'), '--target-dir', targetDirectory, '--features', 'ios-ffi',
    '--target', target, '--lib', '--crate-type', 'staticlib'],
  { RUSTC: compiler, SDKROOT: sdkRoot, IPHONEOS_DEPLOYMENT_TARGET: '16.4' });
  const library = requireFile(join(targetDirectory, target, 'debug', 'libkloda_pairing_native.a'));
  const exports = run('xcrun', ['nm', '--no-llvm-bc', '-gU', library], {}, true);
  for (const symbol of symbols) assert(new RegExp(`\\b_kloda_ios_${symbol}\\b`).test(exports), `Missing ABI export ${symbol}`);
  libraries.push({ target, sdk, library });
}
// A unique build-output folder preserves previous artifacts instead of deleting/replacing them.
const output = mkdtempSync(join(targetDirectory, 'ios-abi-'));
const framework = join(output, 'KlodaPairingNative.xcframework');
assert(!existsSync(framework));
const headers = join(crate, 'apple', 'include');
requireFile(join(headers, 'KlodaPairingNative.h'));
run('xcodebuild', ['-create-xcframework', ...libraries.flatMap(({library}) => ['-library', library, '-headers', headers]), '-output', framework]);
requireFile(join(framework, 'Info.plist'));
for (const name of ['IosPairingReply.swift', 'IosPairingNativeCall.swift']) {
  copyFileSync(requireFile(join(crate, 'apple', name)), join(output, name));
}
copyFileSync(join(headers, 'KlodaPairingNative.h'), join(output, 'KlodaPairingNative.h'));
// CocoaPods does not enumerate this generated package through a directory symlink.
const published = join(root, 'apps/mobile/modules/my-module/ios/NativePairing');
const staged = join(output, 'pod-package');
cpSync(framework, join(staged, 'KlodaPairingNative.xcframework'), { recursive: true });
for (const name of ['IosPairingReply.swift', 'IosPairingNativeCall.swift', 'KlodaPairingNative.h']) {
  copyFileSync(join(output, name), join(staged, name));
}
writeFileSync(join(staged, '.kloda-generated-native'), 'Generated by tools/build-native-ios.mjs\n');
const previous = join(output, 'previous-pod-package');
let moved = false;
if (existsSync(published)) {
  assert(lstatSync(published).isSymbolicLink() || existsSync(join(published, '.kloda-generated-native')),
    'Refusing to replace an unrecognized NativePairing directory');
  renameSync(published, previous);
  moved = true;
}
try { renameSync(staged, published); }
catch (error) { if (moved) renameSync(previous, published); throw error; }
writeFileSync(join(output, 'build.json'), JSON.stringify({ profile: 'debug', minimumIos: '16.4',
  targetSlices: libraries.map(({target,sdk}) => ({target,sdk})), exports: symbols.map(s => `kloda_ios_${s}`),
  framework, published, scope: 'Native packaging; simulator/device/runtime acceptance is separate' }, null, 2) + '\n');
console.log(`iOS_ABI_PACKAGE_VERIFIED_NOT_RUNTIME_ACCEPTANCE ${framework}`);
